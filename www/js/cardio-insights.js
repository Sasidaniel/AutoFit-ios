const ROLES = [['warmup', 'חימום'], ['cooldown', 'שחרור'], ['independent', 'אירובי עצמאי']];
const ACTIVITIES = [['walk', 'הליכה'], ['run', 'ריצה'], ['other', 'פעילות אחרת / לא ידועה']];
const LOCATIONS = [['treadmill', 'הליכון'], ['outside', 'בחוץ'], ['gym', 'חדר כושר'], ['home', 'בית'], ['', 'מיקום לא ידוע']];
const RATINGS = { easy: 'קל', right: 'מתאים', hard: 'קשה' };
const numeric = (value, positive = false) => typeof value === 'number' && Number.isFinite(value)
  && (positive ? value > 0 : value >= 0) ? value : null;
const signedNumeric = (value) => typeof value === 'number' && Number.isFinite(value) ? value : null;
const escape = (value) => String(value ?? '').replace(/[&<>"']/g, (char) =>
  ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char]);
const roleOf = (entry) => ['warmup', 'cooldown'].includes(entry.exerciseId) ? entry.exerciseId : 'independent';
const groupKey = (record) => JSON.stringify([record.role, record.activity, record.location]);

export function cardioRecords(history, now = new Date()) {
  const seen = new Set();
  const records = [];
  for (const workout of Array.isArray(history) ? history : []) {
    const time = Date.parse(workout?.dateISO);
    if (!workout?.id || seen.has(workout.id) || workout.completed === false || !Number.isFinite(time)
      || time > now.getTime() || !Array.isArray(workout.entries)) continue;
    seen.add(workout.id);
    workout.entries.forEach((entry, index) => {
      if (entry?.type !== 'cardio' || entry.completed !== true) return;
      const interval = !!(entry.intervals || entry.exerciseSnapshot?.intervals);
      const activity = !interval && ['walk', 'run'].includes(entry.cardioActivity) ? entry.cardioActivity : 'other';
      const actual = numeric(entry.actualDurationSec);
      records.push({
        workoutId: workout.id, entryIndex: index, dateISO: workout.dateISO, time,
        exerciseId: entry.exerciseId, role: roleOf(entry), activity, interval,
        location: LOCATIONS.some(([id]) => id === entry.location) ? entry.location : '',
        actualDurationSec: actual,
        durationSource: ['manual', 'timer'].includes(entry.cardioDurationSource) ? entry.cardioDurationSource : 'unknown',
        plannedDurationSec: numeric(entry.plannedDurationSec) ?? (actual !== null ? numeric(entry.durationSec) : null),
        legacyDurationSec: actual === null ? numeric(entry.durationSec) : null,
        speedKmh: numeric(entry.speedKmh), incline: signedNumeric(entry.incline),
        inclineUnit: ['level', 'percent'].includes(entry.inclineUnit) ? entry.inclineUnit : null,
        cardioMachineId: typeof entry.cardioMachineId === 'string' ? entry.cardioMachineId.trim() : '',
        difficulty: Object.hasOwn(RATINGS, entry.difficulty) ? entry.difficulty : null,
        pace: typeof entry.pace === 'string' ? entry.pace : '',
      });
    });
  }
  return records.sort((a, b) => b.time - a.time || a.entryIndex - b.entryIndex);
}

export function cardioWeekStart(now = new Date()) {
  const start = new Date(now);
  start.setHours(0, 0, 0, 0);
  start.setDate(start.getDate() - start.getDay());
  return start;
}

export function cardioOverview(history, now = new Date()) {
  const groups = new Map();
  const weekStart = cardioWeekStart(now).getTime();
  for (const record of cardioRecords(history, now)) {
    const key = groupKey(record);
    if (!groups.has(key)) groups.set(key, { key, role: record.role, activity: record.activity,
      location: record.location, records: [], actualSeconds: 0, actualCount: 0, weeklySeconds: 0, weeklyCount: 0,
      legacySeconds: 0, legacyCount: 0, missingCount: 0 });
    const group = groups.get(key);
    group.records.push(record);
    if (record.actualDurationSec !== null) {
      group.actualCount++;
      group.actualSeconds += record.actualDurationSec;
      if (record.time >= weekStart) { group.weeklySeconds += record.actualDurationSec; group.weeklyCount++; }
    } else {
      group.missingCount++;
      if (record.legacyDurationSec !== null) { group.legacySeconds += record.legacyDurationSec; group.legacyCount++; }
    }
  }
  return [...groups.values()];
}

function sameConditions(a, b) {
  if (groupKey(a) !== groupKey(b) || !a.location || a.activity === 'other'
    || a.durationSource !== b.durationSource
    || !(a.speedKmh > 0) || !(b.speedKmh > 0)) return false;
  if (a.speedKmh !== b.speedKmh) return false;
  if (a.cardioMachineId && b.cardioMachineId && a.cardioMachineId !== b.cardioMachineId) return false;
  // Outdoor incline is not presumed to be a measured treadmill setting.
  if (a.location === 'outside') return a.incline === null && b.incline === null;
  if (a.incline === null || b.incline === null || !a.inclineUnit || a.inclineUnit !== b.inclineUnit
    || a.incline !== b.incline) return false;
  return a.inclineUnit !== 'level' || !!a.cardioMachineId && a.cardioMachineId === b.cardioMachineId;
}

export function cardioRecommendation(records) {
  const evidence = [];
  const seen = new Set();
  for (const record of [...records].sort((a, b) => b.time - a.time)) {
    if (record.actualDurationSec > 0 && record.activity !== 'other' && !record.interval && !seen.has(record.workoutId)) {
      seen.add(record.workoutId);
      evidence.push(record);
      if (evidence.length === 2) break;
    }
  }
  const result = (kind, reason) => ({ kind, reason, evidence,
    signature: JSON.stringify(evidence) });
  if (evidence.length < 2 || !evidence[0].location || groupKey(evidence[0]) !== groupKey(evidence[1])) return result('insufficient', 'history');
  const [current, previous] = evidence;
  if (!sameConditions(current, previous)) return result('insufficient', 'conditions');
  if (current.actualDurationSec !== previous.actualDurationSec) return result('insufficient', 'changed');
  if (!current.difficulty || !previous.difficulty) return result('insufficient', 'rating');
  if (current.difficulty === 'hard' || previous.difficulty === 'hard') return result('hold', 'hard');
  const effort = { easy: 0, right: 1, hard: 2 };
  return result('hold', effort[current.difficulty] < effort[previous.difficulty] ? 'lower-effort' : 'same');
}

export function validateCardioGoal(goal) {
  if (!goal || typeof goal.id !== 'string' || !goal.id.trim() || goal.id.length > 100
    || !ROLES.some(([id]) => id === goal.role) || !['walk', 'run'].includes(goal.activity)
    || !LOCATIONS.some(([id]) => !!id && id === goal.location)
    || !['weeklyMinutes', 'sessionMinutes'].includes(goal.metric)
    || numeric(goal.targetMinutes, true) === null
    || goal.targetMinutes > (goal.metric === 'weeklyMinutes' ? 10080 : 1440)) throw new RangeError('Invalid cardio goal');
  const result = { id: goal.id, role: goal.role, activity: goal.activity, location: goal.location,
    metric: goal.metric, targetMinutes: goal.targetMinutes };
  if (goal.speedKmh !== undefined && goal.speedKmh !== null) {
    if (numeric(goal.speedKmh, true) === null) throw new RangeError('Invalid cardio speed');
    result.speedKmh = goal.speedKmh;
  }
  if (goal.incline !== undefined && goal.incline !== null) {
    if (signedNumeric(goal.incline) === null || goal.incline < -100 || goal.incline > 100 || goal.location === 'outside'
      || !['level', 'percent'].includes(goal.inclineUnit || 'level')) throw new RangeError('Invalid cardio incline');
    result.incline = goal.incline;
    result.inclineUnit = goal.inclineUnit || 'level';
    const machine = typeof goal.cardioMachineId === 'string' ? goal.cardioMachineId.trim() : '';
    if (machine.length > 100) throw new RangeError('Invalid cardio machine');
    if (machine) result.cardioMachineId = machine;
  }
  return result;
}

export function saveCardioGoal(settings, goal) {
  const valid = validateCardioGoal(goal);
  const training = settings.training || {};
  const goals = Array.isArray(training.cardioGoals) ? training.cardioGoals : [];
  if (goals.length >= 20 && !goals.some((item) => item.id === valid.id)) throw new RangeError('Too many cardio goals');
  return { ...settings, training: { ...training,
    cardioGoals: [...goals.filter((item) => item.id !== valid.id), valid] } };
}

export function removeCardioGoal(settings, id) {
  return { ...settings, training: { ...(settings.training || {}),
    cardioGoals: (settings.training?.cardioGoals || []).filter((goal) => goal.id !== id) } };
}

export function cardioGoalProgress(history, goal, now = new Date()) {
  const valid = validateCardioGoal(goal);
  const weekStart = cardioWeekStart(now).getTime();
  const comparable = valid.incline === undefined || valid.inclineUnit !== 'level' || !!valid.cardioMachineId;
  const records = cardioRecords(history, now).filter((record) =>
    comparable && record.actualDurationSec !== null && record.activity === valid.activity && record.role === valid.role
    && record.location === valid.location
    && (valid.speedKmh === undefined || valid.speedKmh === record.speedKmh)
    && (valid.incline === undefined || valid.incline === record.incline && valid.inclineUnit === record.inclineUnit
      && (valid.inclineUnit !== 'level' || !!valid.cardioMachineId && valid.cardioMachineId === record.cardioMachineId)
      && (!valid.cardioMachineId || valid.cardioMachineId === record.cardioMachineId)));
  const relevant = valid.metric === 'weeklyMinutes' ? records.filter((record) => record.time >= weekStart) : records;
  // Several entries in the same workout are one session, but roles never mix.
  const latest = relevant[0]?.workoutId;
  const counted = valid.metric === 'weeklyMinutes' ? relevant : relevant.filter((record) => record.workoutId === latest);
  const minutes = counted.reduce((sum, record) => sum + record.actualDurationSec, 0) / 60;
  return { comparable, minutes: comparable ? minutes : null, targetMinutes: valid.targetMinutes,
    percent: comparable ? Math.min(100, minutes / valid.targetMinutes * 100) : null,
    count: counted.length, evidence: counted };
}

